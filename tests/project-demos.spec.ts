import { expect, test } from '@playwright/test'

test('Escala demo traces two fictional PDFs and lets a phone user inspect a day by keyboard', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 650 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/?projeto=escalas#construo')
  const demo = page.locator('.rota-demo')
  await expect(demo.getByRole('heading', { name: 'Da caixa de correio ao calendário' })).toBeVisible()
  await expect(demo.getByText('Demonstração com dados fictícios')).toBeVisible()
  await expect(demo.locator('pre')).toContainText('rota-a-demo.pdf')
  await expect(demo.locator('pre')).toContainText('rota-b-demo.pdf')
  await demo.getByRole('button', { name: 'Executar simulação' }).click()
  await expect(demo.getByRole('button', { name: 'Pausar simulação' })).toBeVisible()
  await expect(demo.getByRole('button', { name: /Identificar anexos/ })).toHaveAttribute('aria-current', 'step')
  await demo.getByRole('button', { name: 'Pausar simulação' }).click()
  await expect(demo.getByRole('button', { name: 'Continuar simulação' })).toBeVisible()
  await demo.getByRole('button', { name: 'Avançar uma etapa' }).click()
  await expect(demo.getByRole('button', { name: /Ler linhas/ })).toHaveAttribute('aria-current', 'step')
  await demo.getByRole('button', { name: /Ver o dia/ }).click()
  await expect(demo.locator('pre')).toContainText('"status": "working"')
  const today = demo.getByRole('button', { name: /15 de junho.*Em serviço/ })
  await today.focus()
  await page.keyboard.press('ArrowRight')
  await expect(demo.getByRole('button', { name: /16 de junho.*Folga/ })).toBeFocused()
  await expect(demo.locator('pre')).toContainText('"status": "day_off"')
  await expect(demo.locator('.rota-day dd')).toContainText('08:00 · Parque A')
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(320)
  await page.getByRole('button', { name: /English/ }).click()
  await expect(demo.getByRole('heading', { name: 'From inbox to calendar' })).toBeVisible()
  await expect(demo.locator('pre')).toContainText('"date": "2026-06-16"')
  await demo.getByRole('button', { name: 'Reset simulation' }).click()
  await expect(demo.getByRole('button', { name: /Receive email/ })).toHaveAttribute('aria-current', 'step')
})

test('PG gallery loads all three screenshots and supports arrow keys, captions and Escape', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/?projeto=pg-guia#construo')
  const gallery = page.getByRole('region', { name: 'Capturas da aplicação · PG Guia de Bolso' })
  await expect(gallery.getByRole('button', { name: /Ampliar/ })).toHaveCount(3)
  const thumb = gallery.getByRole('button', { name: /Ampliar · Início/ })
  await thumb.click()
  const dialog = page.getByRole('dialog', { name: 'PG Guia de Bolso' })
  await expect(dialog).toBeVisible()
  await expect(dialog.getByText('1 / 3')).toBeVisible()
  for (const [index, name] of ['pg-inicio', 'pg-lojas', 'pg-mapa'].entries()) {
    if (index > 0) await page.keyboard.press('ArrowRight')
    const img = dialog.getByRole('img')
    await expect(img).toHaveAttribute('src', new RegExp(name + '\\.webp$'))
    expect(await img.evaluate(async image => {
      if (!(image instanceof HTMLImageElement)) return false
      await image.decode()
      return image.naturalWidth > 0
    })).toBe(true)
  }
  await expect(dialog.getByText('Mapa · Orientar-se por piso')).toBeVisible()
  await expect(dialog.getByRole('img')).toBeInViewport()
  await page.keyboard.press('Escape')
  await expect(dialog).toBeHidden()
  await expect(thumb).toBeFocused()
})
